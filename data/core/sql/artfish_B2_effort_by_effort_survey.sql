SELECT 
s.YEAR as year, 
s.CL_APP_MONTH_ID as month, 
s.DAYS as day, 
site.CL_STAT_STRATA_ID as minor_strata,
s.CL_FISH_LANDING_SITE_ID as landing_site,
s.CL_FISH_FISHING_UNIT_ID as fishing_unit,
s.NB_ACTIVE_FISHING_UNITS as fleet_engagement_number,
q.NB_FISHING_UNITS as fleet_engagement_max 
FROM dt_effort_surveys as s 
LEFT JOIN (SELECT YEAR, CL_APP_MONTH_ID, CL_FISH_LANDING_SITE_ID, CL_FISH_FISHING_UNIT_ID, max(NB_ACTIVE_FISHING_UNITS) as NB_FISHING_UNITS from dt_effort_surveys 
GROUP BY YEAR, CL_APP_MONTH_ID, CL_FISH_LANDING_SITE_ID, CL_FISH_FISHING_UNIT_ID) as q 
ON q.YEAR = s.YEAR AND 
q.CL_APP_MONTH_ID = s.CL_APP_MONTH_ID AND 
q.CL_FISH_LANDING_SITE_ID = s.CL_FISH_LANDING_SITE_ID AND 
q.CL_FISH_FISHING_UNIT_ID = s.CL_FISH_FISHING_UNIT_ID 
LEFT JOIN cl_fish_landing_sites as site  
ON s.CL_FISH_LANDING_SITE_ID = site.ID 
